n=int(input("Entrer un entier compris entre 0 et 6 :"))

if n==0 :
    print("Dimenche")
elif n==1 :
    print("Lundi")
elif n==2 :
    print("Mardi")
elif n==3 :
    print("Mercredi")
elif n==4 :
    print("Jeudi")
elif n==5 :
    print("Vendredi")
elif n==6 :
    print("Samedi")
else :
    print("le nombre saisi en dehors de [0,6]")
    